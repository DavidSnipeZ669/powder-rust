//! Runs a Powder-format `game_postprocess.lua`.
//!
//! Contract (recovered from PowderRecorderCli's LuaPostprocessor):
//!   package.path is set, then `require 'game_postprocess'` must return a table with
//!     get_fps()                -> integer frames per second to sample
//!     get_paddle_ocr_config()  -> { crops = { {cropName, cropCoords={l,t,r,b}, detectorDilateDiameter,
//!                                   detectorMinimumArea, detectorMargin, recogniserStretchVertical,
//!                                   restrictedCharacters, debug}, ... } }        (optional)
//!     get_ocr_config()         -> legacy Tesseract crops {cropName, cropCoords, restrictedCharacters, ...} (optional)
//!     computeEvents(modelOutputs, ocrOutput, frameTimes, paddleOcrOutput)
//!         -> { events = { {name, begin_frame_time}, ... }, TCT_values = {...}, TCT_descriptions = {...} }

use anyhow::{anyhow, Context, Result};
use mlua::{Function, Lua, LuaSerdeExt, Table, Value};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::path::Path;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CropSpec {
    pub name: String,
    /// left, top, right, bottom as fractions of the frame
    pub coords: [f32; 4],
    pub dilate_diameter: i32,
    pub min_area: i32,
    pub margin: i32,
    pub stretch_vertical: bool,
    pub restricted_chars: String,
    pub debug: bool,
    /// true for crops coming from the legacy get_ocr_config (Tesseract-style output)
    pub legacy: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct DetectedEvent {
    pub name: String,
    pub time_sec: f64,
}

#[derive(Debug, Default, Serialize)]
pub struct LuaResult {
    pub events: Vec<DetectedEvent>,
    pub tct_values: BTreeMap<String, Vec<f64>>,
    pub tct_descriptions: BTreeMap<String, Vec<String>>,
}

pub struct GameScript {
    lua: Lua,
    module: Table,
}

fn lua_path_entry(dir: &Path) -> String {
    let d = dir.to_string_lossy().replace('\\', "/");
    format!("{d}/?.lua;{d}/?/init.lua")
}

impl GameScript {
    /// `game_dir` holds game_postprocess.lua; `lib_dirs` hold the `postprocess/` helper modules.
    pub fn load(game_dir: &Path, lib_dirs: &[&Path]) -> Result<Self> {
        Self::load_with_fps(game_dir, lib_dirs, None)
    }

    /// `fps` is exposed to scripts as the global POWDER_RS_FPS (time-based scripts use it;
    /// original Powder scripts ignore it and keep their own get_fps()).
    pub fn load_with_fps(game_dir: &Path, lib_dirs: &[&Path], fps: Option<f64>) -> Result<Self> {
        let lua = Lua::new();
        if let Some(f) = fps {
            lua.globals().set("POWDER_RS_FPS", f)?;
        }
        let mut paths = vec![lua_path_entry(game_dir)];
        for l in lib_dirs {
            paths.push(lua_path_entry(l));
        }
        let package: Table = lua.globals().get("package")?;
        package.set("path", paths.join(";"))?;
        let module: Table = lua
            .load("return require 'game_postprocess'")
            .set_name("powder-rs loader")
            .eval()
            .map_err(|e| anyhow!("loading {}/game_postprocess.lua failed:\n{e}", game_dir.display()))?;
        Ok(Self { lua, module })
    }

    /// Scripts generated by powder-rs set TIME_BASED = true in their module table.
    pub fn is_time_based(&self) -> bool {
        self.module.get::<Option<bool>>("time_based").ok().flatten().unwrap_or(false)
    }

    pub fn fps(&self) -> Result<f64> {
        let f: Option<Function> = self.module.get("get_fps")?;
        Ok(match f {
            Some(f) => f.call::<f64>(()).map_err(|e| anyhow!("get_fps(): {e}"))?,
            None => 4.0,
        })
    }

    fn read_crops(&self, func: &str, legacy: bool) -> Result<Vec<CropSpec>> {
        let f: Option<Function> = self.module.get(func)?;
        let Some(f) = f else { return Ok(vec![]) };
        let cfg: Table = f.call(()).map_err(|e| anyhow!("{func}(): {e}"))?;
        let crops: Option<Table> = cfg.get("crops")?;
        let Some(crops) = crops else { return Ok(vec![]) };
        let mut out = Vec::new();
        for c in crops.sequence_values::<Table>() {
            let c = c?;
            let name: String = c.get("cropName").context("crop is missing cropName")?;
            // Paddle configs use cropCoords = {l,t,r,b}; legacy Tesseract configs use left/upper/right/lower.
            let coords: Vec<f32> = match c.get::<Option<Vec<f32>>>("cropCoords")? {
                Some(v) => v,
                None => {
                    let k = |n: &str| c.get::<Option<f32>>(n).ok().flatten();
                    match (k("left"), k("upper"), k("right"), k("lower")) {
                        (Some(l), Some(t), Some(r), Some(b)) => vec![l, t, r, b],
                        _ => return Err(anyhow!("crop {name}: needs cropCoords = {{left, top, right, bottom}}")),
                    }
                }
            };
            if coords.len() != 4 {
                return Err(anyhow!("crop {name}: cropCoords must have 4 numbers (left, top, right, bottom)"));
            }
            let get_i = |k: &str, d: i32| -> i32 { c.get::<Option<i32>>(k).ok().flatten().unwrap_or(d) };
            out.push(CropSpec {
                coords: [coords[0], coords[1], coords[2], coords[3]],
                dilate_diameter: get_i("detectorDilateDiameter", 5),
                min_area: get_i("detectorMinimumArea", 50),
                margin: get_i("detectorMargin", 10),
                stretch_vertical: c.get::<Option<bool>>("recogniserStretchVertical")?.unwrap_or(false),
                restricted_chars: c.get::<Option<String>>("restrictedCharacters")?.unwrap_or_default(),
                debug: c.get::<Option<bool>>("debug")?.unwrap_or(false),
                legacy,
                name,
            });
        }
        Ok(out)
    }

    pub fn ocr_crops(&self) -> Result<Vec<CropSpec>> {
        let mut v = self.read_crops("get_paddle_ocr_config", false)?;
        v.extend(self.read_crops("get_ocr_config", true)?);
        Ok(v)
    }

    pub fn compute_events(
        &self,
        model_outputs: &BTreeMap<String, Vec<f32>>,
        legacy_ocr: &BTreeMap<String, (Vec<String>, Vec<f32>)>,
        frame_times: &[f64],
        paddle_ocr: &BTreeMap<String, Vec<String>>,
    ) -> Result<LuaResult> {
        let lua = &self.lua;
        let mo = lua.create_table()?;
        for (k, v) in model_outputs {
            mo.set(k.as_str(), lua.create_sequence_from(v.iter().copied())?)?;
        }
        self.call_compute(mo, legacy_ocr, frame_times, paddle_ocr)
    }

    /// Dry run where every visual cue the script asks for exists (all zeros).
    pub fn compute_events_dry(
        &self,
        legacy_ocr: &BTreeMap<String, (Vec<String>, Vec<f32>)>,
        frame_times: &[f64],
        paddle_ocr: &BTreeMap<String, Vec<String>>,
    ) -> Result<LuaResult> {
        let mo: Table = self
            .lua
            .load("local n = ... ; local z = {} ; for i = 1, n do z[i] = 0 end ; return setmetatable({ ['__powder_rs_dummy'] = z }, { __index = function() return z end })")
            .call(frame_times.len())?;
        self.call_compute(mo, legacy_ocr, frame_times, paddle_ocr)
    }

    fn call_compute(
        &self,
        mo: Table,
        legacy_ocr: &BTreeMap<String, (Vec<String>, Vec<f32>)>,
        frame_times: &[f64],
        paddle_ocr: &BTreeMap<String, Vec<String>>,
    ) -> Result<LuaResult> {
        let lua = &self.lua;
        let lo = lua.create_table()?;
        for (k, (r, c)) in legacy_ocr {
            let t = lua.create_table()?;
            t.set("results", lua.create_sequence_from(r.iter().map(|s| s.as_str()))?)?;
            t.set("confidences", lua.create_sequence_from(c.iter().copied())?)?;
            lo.set(k.as_str(), t)?;
        }
        let po = lua.create_table()?;
        for (k, r) in paddle_ocr {
            let t = lua.create_table()?;
            t.set("results", lua.create_sequence_from(r.iter().map(|s| s.as_str()))?)?;
            po.set(k.as_str(), t)?;
        }
        let ft = lua.create_sequence_from(frame_times.iter().copied())?;
        let f: Function = self.module.get("computeEvents").context("game_postprocess.lua has no computeEvents")?;
        let res: Table = f.call((mo, lo, ft, po)).map_err(|e| anyhow!("computeEvents failed:\n{e}"))?;

        let mut out = LuaResult::default();
        if let Some(events) = res.get::<Option<Table>>("events")? {
            for e in events.sequence_values::<Table>() {
                let e = e?;
                let name: String = e.get("name")?;
                let t: Option<f64> = e.get("begin_frame_time")?;
                out.events.push(DetectedEvent { name, time_sec: t.unwrap_or(0.0) });
            }
        }
        for (key, field) in [("TCT_values", true), ("TCT_descriptions", false)] {
            if let Some(t) = res.get::<Option<Table>>(key)? {
                for pair in t.pairs::<String, Value>() {
                    let (k, v) = pair?;
                    if field {
                        let v: Vec<f64> = lua.from_value(v).unwrap_or_default();
                        out.tct_values.insert(k, v);
                    } else {
                        let v: Vec<String> = lua.from_value(v).unwrap_or_default();
                        out.tct_descriptions.insert(k, v);
                    }
                }
            }
        }
        out.events.sort_by(|a, b| a.time_sec.total_cmp(&b.time_sec).then_with(|| a.name.cmp(&b.name)));
        Ok(out)
    }
}
